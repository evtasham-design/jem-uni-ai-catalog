function getVisibleTags(service) {
  const categoryLabels = new Set(categories.flatMap((category) => Object.values(category.label)));
  const tags = uniqueTags([service.category[state.lang]]
    .filter(Boolean)
    .map((tag) => String(tag).trim()));
  const extra = [...(service.subCategories || []), ...service.tags]
    .filter((tag) => tag && tag.length <= 26 && isVisibleTag(tag, categoryLabels))
    .filter((tag) => !tags.some((visibleTag) => normalize(visibleTag) === normalize(tag)))
    .slice(0, 3);
  return uniqueTags([...tags, ...extra]).slice(0, 4);
}

function uniqueTags(tags) {
  const seen = new Set();
  return tags.filter((tag) => {
    const key = normalize(tag);
    if (!key || seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

function isVisibleTag(tag, categoryLabels) {
  const value = String(tag || "").trim();
  if (!value || categoryLabels.has(value)) return false;
  if (value.length > 34) return false;
  if (/подпис|телеграм|telegram|канал|если было полезно|@/i.test(value)) return false;
  const normalizedTag = normalize(value).replace(/\s+/g, " ");
  if (normalizedTag.includes("600 ai tools") || normalizedTag.includes("ai services") || normalizedTag.includes("ai servi")) {
    return false;
  }
  if (state.lang === "ru" && /[іїєґІЇЄҐ]/.test(value)) return false;
  if (state.lang === "uk" && /[а-яёіїєґ]/i.test(value) && !/[іїєґІЇЄҐ]/.test(value)) return false;
  if (state.lang === "en" && /[а-яёіїєґ]/i.test(value)) return false;
  return true;
}

function buildSearchText(service) {
  return normalize(
    [
      service.name,
      service.url,
      service.domain,
      service.category?.ru,
      service.category?.uk,
      service.category?.en,
      ...(service.subCategories || []),
      ...(service.tags || []),
      service.description?.ru,
      service.description?.uk,
      service.description?.en,
      service.pricing,
    ].join(" "),
  );
}

function normalize(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();
}

function initials(name) {
  return String(name || "AI")
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((word) => word[0])
    .join("")
    .toUpperCase();
}

function formatNumber(value) {
  return new Intl.NumberFormat(state.lang === "en" ? "en-US" : state.lang === "uk" ? "uk-UA" : "ru-RU").format(value);
}

function t(key) {
  return translations[state.lang]?.[key] || translations.ru[key] || key;
}

function escapeHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function escapeAttr(value) {
  return escapeHtml(value).replaceAll("`", "&#096;");
}
